        private void ZoomtoRowID(int rowID)
        {
                RunInTransaction(() =>
                {
                    PlantProject currentProject = PlantApplication.CurrentProject;
                    Project pipingProj = currentProject.ProjectParts["Piping"];
                    DataLinksManager dlm = pipingProj.DataLinksManager;
                    Editor ed = Autodesk.AutoCAD.ApplicationServices.Application.DocumentManager.MdiActiveDocument.Editor;

                    var TargetObjectIDRaw = dlm.FindAcPpObjectIds(rowID);
                    /*Before understanding What we've done here, you should know the difference between RowID and ObjectID.
                    RowID is the ID of the row in the database, while ObjectID is the ID of the object in the AutoCAD drawing. Several points:
                    1- ObjectID changes everytime you open and close ACP3D.
                    2- Each RowID MAY point to several ObjectIDs. Thats why the output of this method would be an ACP3D special object type for ARRAYS*/

                    ObjectId TargetObjectID = ObjectId.Null;

                    foreach (var objId in TargetObjectIDRaw)
                    /*The reason we are doing it is that we do not have access to any specific member of this ACP3D custom array.
                    So we loop through it and choose the first one and then break out of the loop.*/
                    {
                        TargetObjectID = dlm.MakeAcDbObjectId(objId);
                        //This is obvious. We turn the custom object ID to the AutoCAD ObjectID so we can use it to querry the drawing.

                        if (TargetObjectID != ObjectId.Null)
                        {
                            break;
                        }
                    }

                    if (TargetObjectID != ObjectId.Null)
                    {
                        Transaction tr = HostApplicationServices.WorkingDatabase.TransactionManager.TopTransaction;
                        /*You know that you cannot access the tr inside your RunInTransaction method, but ACP3D has a special method to access the current open transaction.
                        Line of code above is how to use this*/

                        Entity TargetEntity = tr.GetObject(TargetObjectID, OpenMode.ForRead) as Entity;
                        if (TargetEntity == null) return;

                        Extents3d TargetExtents = TargetEntity.GeometricExtents;
                        //This is interesting. You have an ObjectID and by only that, you can have the cooridnates of a box which contains your 3d model completly.

                        ViewTableRecord CurrView = ed.GetCurrentView();
                        double centerX = (TargetExtents.MinPoint.X + TargetExtents.MaxPoint.X) / 2;
                        double centerY = (TargetExtents.MinPoint.Y + TargetExtents.MaxPoint.Y) / 2;
                        double centerZ = (TargetExtents.MinPoint.Z + TargetExtents.MaxPoint.Z) / 2;
                        //these two are obvious. We are pointing to the center of the box X and Y.

                        double width = TargetExtents.MaxPoint.X - TargetExtents.MinPoint.X;
                        double height = TargetExtents.MaxPoint.Y - TargetExtents.MinPoint.Y;
                        /*About these two: the width and height of the box is not the width and height of the object.
                        It is the width and height of the box that contains the object. Therefore, you calculate this based on your target volume*/

                        CurrView.Target = new Point3d(centerX, centerY, centerZ);
                        CurrView.CenterPoint = Point2d.Origin;
                        CurrView.Width = width * 1.5;
                        CurrView.Height = height * 1.5;
                        /*Several points here: 1-There is a difference between Target and CenterPoint. Target is rotating reference point, while the CenterPoint
                        is the distance you panned from that reference point. 2- We multiply 1.5 for width and height to prevent the object touching the edges of
                        screen.*/

                        ed.SetCurrentView(CurrView);
                        ed.UpdateScreen();
                        ed.SetImpliedSelection(new ObjectId[] { TargetObjectID });
                        //The syntax for changing the view and updating the screen to show the new view and actually selecting the element.

                    }
                    else
                    {
                        ed.WriteMessage($"\nNo AutoCAD object found for Row ID {rowID}.");
                    }

                });
        }

        private void MoveRowID(double Xdist, double Ydist, double Zdist)
        {
            Editor ed = Autodesk.AutoCAD.ApplicationServices.Application.DocumentManager.MdiActiveDocument.Editor;

            RunInTransaction(() =>
            {
                Vector3d MoveVector = new Vector3d(Xdist, Ydist, Zdist);

                PromptSelectionResult SelRes = ed.SelectImplied();

                if (SelRes.Status != PromptStatus.OK)
                {
                    ed.WriteMessage("\nNo object selected to move.");
                    return;
                }

                SelectionSet selSet = SelRes.Value;

                Transaction tr = HostApplicationServices.WorkingDatabase.TransactionManager.TopTransaction;
                /* I am gonna tell this again. When you create a Trasaction at the top of this code, you already opened a transaction. Meaning that you cannot open another one inside it
                whenever you want. You are gonna use that opened transaction and do what you want.*/

                foreach (SelectedObject selObj in selSet)
                {
                    Entity ent = tr.GetObject(selObj.ObjectId, OpenMode.ForWrite) as Entity;

                    ent.TransformBy(Matrix3d.Displacement(MoveVector));
                }
            });
        }

        public List<CompData> SelectedItems()
        {
            Editor ed = Autodesk.AutoCAD.ApplicationServices.Application.DocumentManager.MdiActiveDocument.Editor;
            PlantProject currentProject = PlantApplication.CurrentProject;
            Project pipingProj = currentProject.ProjectParts["Piping"];
            DataLinksManager dlm = pipingProj.DataLinksManager;

            PromptSelectionResult SelRes = ed.SelectImplied();
            //This is how we get the selected elements.

            SelectionSet selSet ;
            List<CompData> SelItems = new List<CompData>();

            if (SelRes.Status != PromptStatus.OK)
            {
                //txtChatHistory.AppendText("\nNo object selected.\n");
                return SelItems;
            }

            else
            {
                selSet = SelRes.Value;
                foreach (SelectedObject selObj in selSet)
                {
                    CompData RawData = new CompData();
                    //Your customized class to store the selected components data.

                    int rowID = -1;

                    try
                    {
                        rowID = dlm.FindAcPpRowId(selObj.ObjectId);
                    }

                    catch { continue; } 
                    //A very simple use of try and catch. If you know you may get exceptions that you dont care about and just want your code to run, this is what you do.
                    
                    if (rowID <= 0)
                    {
                        continue;
                    }

                    else
                    {
                        StringCollection labels = new StringCollection();
                        labels.Add("LineNumberTag");
                        labels.Add("Spec");
                        labels.Add("Size");
                        labels.Add("Tag");
                        labels.Add("Position X");
                        labels.Add("Position Y");
                        labels.Add("Position Z");

                        var results = dlm.GetProperties(rowID, labels, true);

                        RawData.ObjID = selObj.ObjectId.ToString();
                        RawData.LineNo = results[0];
                        RawData.Spec = results[1];
                        RawData.Size = results[2];
                        RawData.Tag = results[3];
                        double.TryParse(results[4], out double coordX);
                        double.TryParse(results[5], out double coordY);
                        double.TryParse(results[6], out double coordZ);
                        RawData.CoordX = coordX;
                        RawData.CoordY = coordY;
                        RawData.CoordZ = coordZ;

                        SelItems.Add(RawData);
                    }
                }
                return SelItems;
            }
        }
