        private void RunInTransaction(Action toolTask)
        /*With this method (toolTask), we are going to create the initial fancy steps of interacting with AutoCAD once,
        and then use it everywhere we want to change the DWG. For example, in here, you have 4 buttons to do 4 different
        things. Instead of repeating the same code for each button, you can just call this method. Action here is a delegate,
        which means it purpose is to be used for a method (unlike other methods which will receive variables).*/
        {
            Document doc = Autodesk.AutoCAD.ApplicationServices.Application.DocumentManager.MdiActiveDocument;
            /*The reason for the long Autodesk.AutoCAD line is that otherwise, there would be a conflict between the Document class in AutoCAD
            and the Document class in WPF, since we are using both of them in this code, we need to specify
            which one we are using by using the full namespace.*/

            if (doc == null) return;
            //Just a safety check for the user not to click without opening a drawing.

            Database db = doc.Database;
            Editor ed = doc.Editor;
            using (DocumentLock docLock = doc.LockDocument())
            /*When you type a command in AutoCAD, it locks the document to prevent other commands from interfering with it.
            If you want to run a command in your palette which is floating freely without locking the document first,
            you would get an error saying that the document is locked by another command which is your palette command.
            so you need to lock the document first before running any command in your palette.
            as for the "using", we did that so the code would automatically dispose the lock after it is done executing.
            since if we do not dispose the lock, it would stay locked and you would not be able to run any other command
            in AutoCAD until you close the drawing.*/
            {
                using (Transaction tr = db.TransactionManager.StartTransaction())
                {
                    try
                    //From now on you gotta use try and cath more often. You know what they are for, so stop being lazy and use them.
                    {
                        toolTask();
                        tr.Commit();
                    }
                    catch (System.Exception ex)
                    {
                        ed.WriteMessage($"Error: {ex.Message}");
                    }
                }
            }
        }

